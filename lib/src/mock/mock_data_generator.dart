import 'dart:convert';

import '../database/database_data_accessor.dart';
import '../models/schema_graph.dart';
import '../models/table_node.dart';
import 'mock_value_inferer.dart';
import 'topological_sorter.dart';

/// Result container for generated mock data across tables.
class MockGenerationResult {
  /// Ordered list of tables generated (topological order).
  final List<TableNode> orderedTables;

  /// Map of `tableName -> List<RowMap>`.
  final Map<String, List<Map<String, dynamic>>> rows;

  /// Pool of primary key values generated per table.
  final Map<String, List<dynamic>> idPool;

  const MockGenerationResult({
    required this.orderedTables,
    required this.rows,
    required this.idPool,
  });

  /// Formats the mock data as an executable PostgreSQL SQL script.
  String toSqlScript() {
    final sb = StringBuffer();
    sb.writeln('-- Auto-generated by Serverpod DevTools Mock Seeder');
    sb.writeln('-- Ordered topologically to satisfy Foreign Key constraints.');
    sb.writeln('BEGIN;');
    sb.writeln();

    for (final table in orderedTables) {
      final tableRows = rows[table.tableName] ?? [];
      if (tableRows.isEmpty) continue;

      sb.writeln('-- Table: ${table.tableName}');
      for (final row in tableRows) {
        final columns = row.keys.toList();
        final columnStr = columns.map((c) => '"$c"').join(', ');
        final valueStr = columns.map((c) => _formatSqlValue(row[c])).join(', ');
        sb.writeln('INSERT INTO "${table.tableName}" ($columnStr) VALUES ($valueStr);');
      }
      sb.writeln();
    }

    sb.writeln('COMMIT;');
    return sb.toString();
  }

  /// Formats the mock data as structured JSON fixtures.
  String toJsonFixtures({bool pretty = true}) {
    final encoder = pretty ? const JsonEncoder.withIndent('  ') : const JsonEncoder();
    return encoder.convert(rows);
  }

  /// Generates a standalone Dart seed script using Serverpod model classes.
  String toDartSeedScript() {
    final sb = StringBuffer();
    sb.writeln('// Auto-generated Serverpod Seed Script');
    sb.writeln('import \'package:serverpod/serverpod.dart\';');
    sb.writeln();
    sb.writeln('Future<void> seedDatabase(Session session) async {');
    sb.writeln('  session.log(\'Seeding mock data in dependency order...\');');
    sb.writeln();

    for (final table in orderedTables) {
      final tableRows = rows[table.tableName] ?? [];
      if (tableRows.isEmpty) continue;

      sb.writeln('  // ${table.className} (${table.tableName})');
      for (final row in tableRows) {
        final jsonStr = jsonEncode(row);
        sb.writeln('  // Insert ${table.className}: $jsonStr');
      }
      sb.writeln();
    }

    sb.writeln('  session.log(\'Mock data seeded successfully.\');');
    sb.writeln('}');
    return sb.toString();
  }

  /// Seeds the generated rows directly into the connected PostgreSQL database.
  Future<Map<String, int>> seedDatabase(DatabaseDataAccessor db) async {
    final stats = <String, int>{};

    for (final table in orderedTables) {
      final tableRows = rows[table.tableName] ?? [];
      var inserted = 0;

      for (final row in tableRows) {
        final columns = row.keys.toList();
        final colList = columns.map((c) => '"$c"').join(', ');
        final valueStr = columns.map((c) => _formatSqlValue(row[c])).join(', ');

        final query = 'INSERT INTO "${table.tableName}" ($colList) VALUES ($valueStr) ON CONFLICT DO NOTHING;';

        try {
          await db.database.unsafeExecute(query);
          inserted++;
        } catch (_) {
          // If constraint error or duplicate, continue
        }
      }

      stats[table.tableName] = inserted;
    }

    return stats;
  }

  static String _formatSqlValue(dynamic val) {
    if (val == null) return 'NULL';
    if (val is num) return val.toString();
    if (val is bool) return val ? 'TRUE' : 'FALSE';
    if (val is List || val is Map) {
      final jsonStr = jsonEncode(val).replaceAll("'", "''");
      return "'$jsonStr'::jsonb";
    }
    final str = val.toString().replaceAll("'", "''");
    return "'$str'";
  }
}

/// Generates mock data for an entire Serverpod [SchemaGraph].
class MockDataGenerator {
  /// Generates mock rows for [graph] adhering to foreign-key dependencies.
  static MockGenerationResult generate({
    required SchemaGraph graph,
    int rowsPerTable = 3,
    Map<String, int>? tableRowCounts,
    List<String>? targetTableNames,
  }) {
    final orderedTables = TopologicalSorter.sortTables(graph);
    final rows = <String, List<Map<String, dynamic>>>{};
    final idPool = <String, List<dynamic>>{};

    for (final table in orderedTables) {
      if (targetTableNames != null && !targetTableNames.contains(table.tableName)) {
        continue;
      }

      final count = tableRowCounts?[table.tableName] ?? rowsPerTable;
      final tableRows = <Map<String, dynamic>>[];
      final tableIds = <dynamic>[];

      for (var r = 0; r < count; r++) {
        final row = <String, dynamic>{};

        for (final field in table.fields) {
          final val = MockValueInferer.inferValue(
            field: field,
            tableName: table.tableName,
            rowIndex: r,
            idPool: idPool,
          );

          row[field.name] = val;

          // Record primary key for child table references
          if (field.isPrimaryKey || field.name == 'id' || field.name == 'uuid') {
            if (val != null) tableIds.add(val);
          }
        }

        tableRows.add(row);
      }

      rows[table.tableName] = tableRows;
      idPool[table.tableName] = tableIds;
    }

    return MockGenerationResult(
      orderedTables: orderedTables,
      rows: rows,
      idPool: idPool,
    );
  }
}
